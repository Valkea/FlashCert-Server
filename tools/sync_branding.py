#!/usr/bin/env python3
"""Import web branding from a local FlashCert Android checkout.

Usage: python tools/sync_branding.py ../FlashCert-android
Generated assets are checked in; the Android checkout is not needed at runtime.
"""
import importlib.util
from pathlib import Path
import shutil
import sys


def main():
    app = Path(sys.argv[1]).resolve()
    sys.path.insert(0, str(app / "tools"))
    spec = importlib.util.spec_from_file_location("palettes", app / "tools/palettes.py")
    palettes = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(palettes)
    static = Path(__file__).resolve().parents[1] / "src/flashcert_share/static"
    mapping = {"text_muted": "muted", "highlight": "mark"}
    css = ["/* Generated by tools/sync_branding.py from the Android palettes. */"]
    for night, system in ((False, False), (True, False), (True, True)):
        if system:
            css.append("@media (prefers-color-scheme: dark) {")
        for pid, _, light, dark, *fixed in palettes.PALETTES:
            selector = f':root[data-palette="{pid}"]'
            if pid == palettes.DEFAULT:
                selector = ":root:not([data-palette]), " + selector
            if night:
                theme = ':not([data-theme="light"]):not([data-theme="dark"])' if system else '[data-theme="dark"]'
                selector = selector.replace(":root", ":root" + theme)
            css.append(selector + " {")
            values = palettes.roles(dark if night else light, night, light["text"])
            if fixed:
                values.update(fixed[0]["night" if night else "light"])
            for role, value in values.items():
                if len(value) == 8:  # Android ARGB -> CSS RGBA
                    value = value[2:] + value[:2]
                css.append(f"  --{mapping.get(role, role.replace('_', '-'))}: #{value};")
            css.append("  color-scheme: " + ("dark;" if night else "light;"))
            css.append("}")
        if system:
            css.append("}")
    (static / "palettes.css").write_text("\n".join(css) + "\n")
    d = palettes.spiral.path()
    logo = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="27 27 54 54">'
            f'<path fill="var(--accent-text, #0A64C9)" d="{d}"/>'
            f'<path fill="var(--spark, #C705A5)" d="{palettes.spiral.CORE}"/></svg>\n')
    # Inline symbol allows the header logo to follow the selected palette.
    (static / "logo.svg").write_text(logo)
    stops = "".join(f'<stop offset="{o}" stop-color="#{c}"/>' for o, c in palettes.ICONS[palettes.DEFAULT])
    icon = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="27 27 54 54">'
            f'<defs><radialGradient id="spiral" gradientUnits="userSpaceOnUse" cx="54" cy="54" r="27">{stops}</radialGradient></defs>'
            f'<rect x="27" y="27" width="54" height="54" rx="14" fill="#fff"/>'
            f'<path fill="url(#spiral)" d="{d}"/></svg>\n')
    (static / "icon.svg").write_text(icon)
    (static.parent / "templates/_logo.html").write_text(logo.replace('<svg ', '<svg class="brand-mark" aria-hidden="true" '))
    fonts = static / "fonts"
    fonts.mkdir(exist_ok=True)
    shutil.copyfile(app / "app/src/main/res/font/grotesk_bold.ttf", fonts / "grotesk_bold.ttf")
    shutil.copyfile(app / "app/src/main/assets/licenses/SpaceGrotesk-OFL.txt", fonts / "SpaceGrotesk-OFL.txt")


if __name__ == "__main__":
    main()
